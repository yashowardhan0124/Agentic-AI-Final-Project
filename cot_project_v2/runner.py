"""
Shared machinery for running a prompting condition over every problem and
every run: response cache (so an interrupted run resumes where it stopped),
per-trial transcript logs, progress + ETA, and results files.
"""

import hashlib
import json
import os
import time

import config
from grading import extract_answer, is_correct
from problems import PROBLEMS
from prompts import build_prompt


def make_client(mock: bool, model: str):
    if mock:
        from mock_client import MockClient
        return MockClient(model)
    from ollama_client import OllamaClient
    return OllamaClient(model)


# ---- run metadata ---------------------------------------------------------
def save_meta(out_dir: str, meta: dict):
    path = os.path.join(out_dir, "run_config.json")
    existing = load_meta(out_dir) or {}
    existing.update(meta)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(existing, f, indent=2)


def load_meta(out_dir: str):
    path = os.path.join(out_dir, "run_config.json")
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as f:
        return json.load(f)


# ---- cache ------------------------------------------------------------------
class Cache:
    def __init__(self, out_dir: str, enabled: bool = True):
        self.path = os.path.join(out_dir, "cache.jsonl")
        self.enabled = enabled
        self.data = {}
        if enabled and os.path.exists(self.path):
            with open(self.path, encoding="utf-8") as f:
                for line in f:
                    try:
                        row = json.loads(line)
                        self.data[row["key"]] = row["response"]
                    except (json.JSONDecodeError, KeyError):
                        continue  # half-written last line after a crash

    @staticmethod
    def key(model, prompt, temperature, seed):
        raw = f"{model}|{temperature}|{seed}|{config.NUM_PREDICT}|{prompt}"
        return hashlib.sha256(raw.encode()).hexdigest()

    def get(self, k):
        return self.data.get(k) if self.enabled else None

    def put(self, k, response):
        self.data[k] = response
        with open(self.path, "a", encoding="utf-8") as f:
            f.write(json.dumps({"key": k, "response": response}) + "\n")


# ---- running ----------------------------------------------------------------
def write_log(path, prompt, raw, trial, mock):
    with open(path, "w", encoding="utf-8") as f:
        if mock:
            f.write("*** MOCK DATA -- generated by mock_client.py, NOT a real model ***\n\n")
        f.write(f"CONDITION: {trial['condition']}   RUN: {trial['run']}   "
                f"temperature={trial['temperature']} seed={trial['seed']}\n\n")
        f.write(f"PROMPT:\n{prompt}\n\n---\n\nRAW MODEL OUTPUT:\n{raw}\n\n---\n")
        f.write(f"Extracted answer: {trial['predicted']}  (via {trial['extraction_method']})\n")
        f.write(f"Expected answer:  {trial['expected']}\n")
        f.write(f"Correct: {trial['correct']}\n")
        f.write(f"Output tokens: {trial['output_tokens']}   Latency: {trial['latency_s']} s\n")


def run_condition(condition, client, out_dir, runs, cache, mock):
    trials = []
    total = len(PROBLEMS) * runs
    done = 0
    t_start = time.time()
    model_calls = 0
    for run in range(runs):
        settings = config.run_settings(run)
        for problem in PROBLEMS:
            prompt = build_prompt(condition, problem["question"])
            k = Cache.key(client.model, prompt, settings["temperature"], settings["seed"])
            resp = cache.get(k)
            if resp is None:
                resp = client.generate(prompt, settings["temperature"], settings["seed"])
                cache.put(k, resp)
                model_calls += 1
            pred, method = extract_answer(resp["text"])
            trial = {
                "problem_id": problem["id"],
                "condition": condition,
                "run": run,
                "temperature": settings["temperature"],
                "seed": settings["seed"],
                "prompt": prompt,
                "raw_output": resp["text"],
                "predicted": pred,
                "extraction_method": method,
                "expected": problem["answer"],
                "correct": is_correct(pred, problem["answer"], problem["tolerance"]),
                "output_tokens": resp.get("output_tokens"),
                "prompt_tokens": resp.get("prompt_tokens"),
                "latency_s": resp.get("latency_s"),
            }
            log_path = os.path.join(out_dir, "logs",
                                    f"{problem['id']}_{condition}_run{run}.txt")
            trial["log_file"] = log_path
            write_log(log_path, prompt, resp["text"], trial, mock)
            trials.append(trial)

            done += 1
            elapsed = time.time() - t_start
            eta = ""
            if model_calls:
                rate = elapsed / model_calls
                remaining = (total - done) * rate
                eta = f"  ETA {remaining / 60:.1f} min"
            mark = "PASS" if trial["correct"] else "FAIL"
            print(f"  [{condition:10s}] run {run} {problem['id']:24s} "
                  f"pred={pred!s:>9} expected={problem['answer']!s:>7} {mark}"
                  f"  ({done}/{total}){eta}")
    return trials


def results_path(out_dir, condition):
    return os.path.join(out_dir, f"results_{condition}.json")


def save_results(out_dir, condition, trials):
    with open(results_path(out_dir, condition), "w", encoding="utf-8") as f:
        json.dump(trials, f, indent=2)


def load_results(out_dir, condition):
    path = results_path(out_dir, condition)
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def load_all(out_dir):
    out = {}
    for c in config.CONDITIONS:
        r = load_results(out_dir, c)
        if r is not None:
            out[c] = r
    return out
